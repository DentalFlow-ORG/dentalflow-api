-- Aligns the AuditAction enum with prisma/schema.prisma.
--
-- 20260604230209_remove_internal_leads rebuilds this enum from a hard-coded
-- list that had already gone stale when it was written. That list drops values
-- the application writes today (USER_LOGIN_SUCCESS, every PATIENT_*,
-- CLINICAL_RECORD_*, GOOGLE_CALENDAR_* and PRIVACY_* action) and invents
-- values the schema has never had (STOCK_ITEM_CREATED, FISCAL_PROFILE_UPDATED,
-- AVAILABILITY_*, and others). A database built from that history ends up with
-- an enum the Prisma client cannot write to.
--
-- This migration restores the enum to exactly the set in schema.prisma, and is
-- a no-op where that is already the case -- including a database that still
-- carries the LEAD_* values because the removal migration never ran there.
--
-- Rows holding a value that no longer exists (LEAD_CREATED, or one of the
-- invented ones) are mapped to OTHER rather than dropped: an audit log is
-- evidence, and losing the row would be worse than losing its precise label.

DO $migration$
BEGIN
  IF (
    SELECT COALESCE(array_agg(e.enumlabel::text ORDER BY e.enumlabel::text), ARRAY[]::text[])
    FROM pg_enum e
    JOIN pg_type t ON t.oid = e.enumtypid
    WHERE t.typname = 'AuditAction'
  ) IS DISTINCT FROM (
    SELECT array_agg(v ORDER BY v)
    FROM unnest(ARRAY[
      'USER_LOGIN_SUCCESS', 'USER_LOGIN_FAILURE', 'USER_LOGOUT',
      'USER_REFRESH_TOKEN', 'USER_REFRESH_TOKEN_FAILED',
      'USER_PASSWORD_CHANGED', 'USER_PASSWORD_RESET_REQUESTED',
      'USER_CREATED', 'USER_UPDATED', 'USER_DEACTIVATED',
      'USER_ROLE_CHANGED', 'PRIVACY_REQUEST_CREATED',
      'PRIVACY_REQUEST_STATUS_CHANGED', 'PRIVACY_REQUEST_RESPONDED',
      'COOKIE_CONSENT_RECORDED', 'TERMS_ACCEPTED', 'APPOINTMENT_CREATED',
      'APPOINTMENT_UPDATED', 'APPOINTMENT_CANCELED',
      'APPOINTMENT_COMPLETED', 'APPOINTMENT_PAYMENT_UPDATED',
      'PATIENT_CREATED', 'PATIENT_UPDATED', 'PATIENT_DELETED',
      'CLINICAL_RECORD_CREATED', 'CLINICAL_RECORD_UPDATED',
      'CLINICAL_RECORD_ACCESSED', 'CLINICAL_RECORD_LOCKED',
      'CLINICAL_RECORD_DELETED', 'GOOGLE_CALENDAR_CONNECTED',
      'GOOGLE_CALENDAR_DISCONNECTED', 'GOOGLE_CALENDAR_SYNCED',
      'SUBSCRIPTION_CREATED', 'SUBSCRIPTION_CANCELED',
      'SUBSCRIPTION_CHANGED', 'NOTIFICATION_SENT',
      'NOTIFICATION_CONSENT_GRANTED', 'NOTIFICATION_CONSENT_REVOKED',
      'REPORT_EXPORTED', 'OTHER'
    ]) AS v
  ) THEN

    ALTER TYPE "AuditAction" RENAME TO "AuditAction_stale";

    CREATE TYPE "AuditAction" AS ENUM (
    'USER_LOGIN_SUCCESS', 'USER_LOGIN_FAILURE', 'USER_LOGOUT',
    'USER_REFRESH_TOKEN', 'USER_REFRESH_TOKEN_FAILED',
    'USER_PASSWORD_CHANGED', 'USER_PASSWORD_RESET_REQUESTED',
    'USER_CREATED', 'USER_UPDATED', 'USER_DEACTIVATED',
    'USER_ROLE_CHANGED', 'PRIVACY_REQUEST_CREATED',
    'PRIVACY_REQUEST_STATUS_CHANGED', 'PRIVACY_REQUEST_RESPONDED',
    'COOKIE_CONSENT_RECORDED', 'TERMS_ACCEPTED', 'APPOINTMENT_CREATED',
    'APPOINTMENT_UPDATED', 'APPOINTMENT_CANCELED', 'APPOINTMENT_COMPLETED',
    'APPOINTMENT_PAYMENT_UPDATED', 'PATIENT_CREATED', 'PATIENT_UPDATED',
    'PATIENT_DELETED', 'CLINICAL_RECORD_CREATED',
    'CLINICAL_RECORD_UPDATED', 'CLINICAL_RECORD_ACCESSED',
    'CLINICAL_RECORD_LOCKED', 'CLINICAL_RECORD_DELETED',
    'GOOGLE_CALENDAR_CONNECTED', 'GOOGLE_CALENDAR_DISCONNECTED',
    'GOOGLE_CALENDAR_SYNCED', 'SUBSCRIPTION_CREATED',
    'SUBSCRIPTION_CANCELED', 'SUBSCRIPTION_CHANGED', 'NOTIFICATION_SENT',
    'NOTIFICATION_CONSENT_GRANTED', 'NOTIFICATION_CONSENT_REVOKED',
    'REPORT_EXPORTED', 'OTHER'
    );

    ALTER TABLE "audit_logs"
      ALTER COLUMN "action" TYPE "AuditAction"
      USING (
        CASE
          WHEN "action"::text IN (
      'USER_LOGIN_SUCCESS', 'USER_LOGIN_FAILURE', 'USER_LOGOUT',
      'USER_REFRESH_TOKEN', 'USER_REFRESH_TOKEN_FAILED',
      'USER_PASSWORD_CHANGED', 'USER_PASSWORD_RESET_REQUESTED',
      'USER_CREATED', 'USER_UPDATED', 'USER_DEACTIVATED',
      'USER_ROLE_CHANGED', 'PRIVACY_REQUEST_CREATED',
      'PRIVACY_REQUEST_STATUS_CHANGED', 'PRIVACY_REQUEST_RESPONDED',
      'COOKIE_CONSENT_RECORDED', 'TERMS_ACCEPTED', 'APPOINTMENT_CREATED',
      'APPOINTMENT_UPDATED', 'APPOINTMENT_CANCELED',
      'APPOINTMENT_COMPLETED', 'APPOINTMENT_PAYMENT_UPDATED',
      'PATIENT_CREATED', 'PATIENT_UPDATED', 'PATIENT_DELETED',
      'CLINICAL_RECORD_CREATED', 'CLINICAL_RECORD_UPDATED',
      'CLINICAL_RECORD_ACCESSED', 'CLINICAL_RECORD_LOCKED',
      'CLINICAL_RECORD_DELETED', 'GOOGLE_CALENDAR_CONNECTED',
      'GOOGLE_CALENDAR_DISCONNECTED', 'GOOGLE_CALENDAR_SYNCED',
      'SUBSCRIPTION_CREATED', 'SUBSCRIPTION_CANCELED',
      'SUBSCRIPTION_CHANGED', 'NOTIFICATION_SENT',
      'NOTIFICATION_CONSENT_GRANTED', 'NOTIFICATION_CONSENT_REVOKED',
      'REPORT_EXPORTED', 'OTHER'
          ) THEN "action"::text
          ELSE 'OTHER'
        END
      )::"AuditAction";

    DROP TYPE "AuditAction_stale";

  END IF;
END
$migration$;
